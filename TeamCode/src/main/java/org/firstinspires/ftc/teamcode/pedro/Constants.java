    public static MecanumConfig drivetrainConfig = new MecanumConfig(c -> {
        c.frontLeftName.set("FL");
        c.frontRightName.set("FR");
        c.backLeftName.set("BL");
        c.backRightName.set("BR");
        c.frontLeftDirection.set(DcMotorSimple.Direction.REVERSE);
        c.frontRightDirection.set(DcMotorSimple.Direction.FORWARD);
        c.backLeftDirection.set(DcMotorSimple.Direction.REVERSE);
        c.backRightDirection.set(DcMotorSimple.Direction.FORWARD);
    });
    public static ForesightConfig foresightConfig = new ForesightConfig(
            c -> {
                Controller primaryTranslationalForward = Controller.proportional(0.373209286992386);
                Controller secondaryTranslationalForward = Controller.proportional(0.13789085920787506);
                Controller primaryTranslationalLateral = Controller.proportional(0.6252841922062347);
                Controller secondaryTranslationalLateral = Controller.proportional(0.23102580111887416);

                c.forwardTranslational.set(Controller.piecewise(secondaryTranslationalForward).put(2.5, primaryTranslationalForward));
                c.strafeTranslational.set(Controller.piecewise(secondaryTranslationalLateral).put(2.5, primaryTranslationalLateral));

                c.coast.set(Controller.proportionalFeedforward(0.011627857139364761));
                c.brake.set(Controller.proportionalFeedforward(0.009883678568460046));

                c.headingFeedback.set(Controller.proportional(5.252535626270305));
                c.headingBrakeCoefficients.set(Vector2D.cartesian(0.06173060469672459, 0.004435608412993437));

                c.linearBrakeCoefficients.set(Matrix.diag(0.1204549417975096, 0.07090043607382647));
                c.quadraticBrakeCoefficients.set(Matrix.diag(0.0011457351642615524, 0.002080191831852678));

                c.maxAchievableForwardVelocity.set(79.44846940555774);
                c.maxAchievableStrafeVelocity.set(62.598689822303854);
                c.naturalForwardDeceleration.set(30.42383554243458);
                c.naturalStrafeDeceleration.set(68.19558056660094);
            }

    );
